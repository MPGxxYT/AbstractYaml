package me.mortaldev.abstractyaml.config2.processor;

import java.util.HashSet;
import java.util.Set;
import javax.lang.model.SourceVersion;
import me.mortaldev.abstractyaml.config2.processor.SchemaReader.Section;
import me.mortaldev.abstractyaml.config2.processor.SchemaReader.Value;

/**
 * Writes the Java source of a wrapper class for a schema read by {@link SchemaReader}.
 *
 * <p>Accessors read the currently loaded config through the shared {@code ConfigManager} on every
 * call, so they never return values from before a reload. Types are written fully qualified, so
 * section names such as {@code map} or {@code string} cannot clash with imports.
 */
final class WrapperWriter {
  private static final String MANAGER = "me.mortaldev.abstractyaml.config2.ConfigManager";
  private static final String INDENT = "    ";

  private final StringBuilder out = new StringBuilder();

  /** Thrown when two keys produce the same Java name. */
  static final class NameClashException extends RuntimeException {
    final Value value;

    NameClashException(String message, Value value) {
      super(message);
      this.value = value;
    }
  }

  static String write(
      String packageName,
      String className,
      String schemaClass,
      SchemaReader.Schema schema,
      boolean makeFinal,
      boolean generateReload) {
    return new WrapperWriter().render(
        packageName, className, schemaClass, schema, makeFinal, generateReload);
  }

  private String render(
      String packageName,
      String className,
      String schemaClass,
      SchemaReader.Schema schema,
      boolean makeFinal,
      boolean generateReload) {
    if (!packageName.isEmpty()) {
      out.append("package ").append(packageName).append(";\n\n");
    }
    out.append("/**\n")
        .append(" * Typed accessors for the {@code ").append(schema.configName).append("} config.\n")
        .append(" *\n")
        .append(" * <p>Generated by AbstractYaml from {@link ").append(schemaClass).append("}.")
        .append(" Do not edit: changes are overwritten on the next build.\n")
        .append(" */\n")
        .append("@javax.annotation.processing.Generated(\"")
        .append(WrapperProcessor.class.getName()).append("\")\n")
        .append("public ").append(makeFinal ? "final " : "").append("class ").append(className)
        .append(" {\n");
    line(1, "private static final java.lang.String CONFIG_NAME = \""
        + escape(schema.configName) + "\";");
    out.append('\n');
    line(1, "private " + className + "() {}");

    Set<String> methods = new HashSet<>();
    for (Value value : schema.root.values) {
      String name = methodName(value, methods);
      accessor(1, value, name,
          MANAGER + ".getInstance().get(CONFIG_NAME)." + value.type().getter
              + "(\"" + escape(value.key()) + "\")");
    }

    Set<String> enclosing = new HashSet<>();
    enclosing.add(className);
    for (Section child : schema.root.children.values()) {
      section(1, child, enclosing, new HashSet<>());
    }

    if (generateReload && !methods.contains("reload")) {
      out.append('\n');
      line(1, "/**");
      line(1, " * Does nothing: accessors always read the currently loaded config. Kept so code");
      line(1, " * written for earlier wrappers still compiles.");
      line(1, " */");
      line(1, "public static void reload() {}");
    }
    out.append("}\n");
    return out.toString();
  }

  private void section(int level, Section section, Set<String> enclosing, Set<String> siblings) {
    String className = className(section.key, enclosing, siblings);
    out.append('\n');
    line(level, "/** Values under {@code " + section.path + "}. */");
    line(level, "public static final class " + className + " {");
    line(level + 1, "private static final java.lang.String PATH = \"" + escape(section.path) + "\";");
    out.append('\n');
    line(level + 1, "private " + className + "() {}");

    Set<String> methods = new HashSet<>();
    for (Value value : section.values) {
      String name = methodName(value, methods);
      accessor(level + 1, value, name,
          MANAGER + ".getInstance().getSection(CONFIG_NAME, PATH)." + value.type().getter
              + "(\"" + escape(value.key()) + "\")");
    }

    Set<String> nested = new HashSet<>(enclosing);
    nested.add(className);
    Set<String> childNames = new HashSet<>();
    for (Section child : section.children.values()) {
      section(level + 1, child, nested, childNames);
    }
    line(level, "}");
  }

  private void accessor(int level, Value value, String name, String expression) {
    out.append('\n');
    if (value.comment() != null && !value.comment().isBlank()) {
      line(level, "/** " + javadoc(value.comment()) + " */");
    }
    line(level, "public static " + value.type().javaType + " " + name + "() {");
    line(level + 1, "return " + expression + ";");
    line(level, "}");
  }

  private void line(int level, String text) {
    out.append(INDENT.repeat(level)).append(text).append('\n');
  }

  // ===== Names =====

  private static String methodName(Value value, Set<String> taken) {
    String name = identifier(words(value.key()), false);
    if (!taken.add(name)) {
      throw new NameClashException(
          "Key '" + value.key() + "' gives the accessor name " + name
              + "(), which another key in the same section already uses",
          value);
    }
    return name;
  }

  /** A nested class name that differs from every enclosing class, as Java requires. */
  private static String className(String key, Set<String> enclosing, Set<String> siblings) {
    String name = identifier(words(key), true);
    if (enclosing.contains(name)) {
      name = name + "Section";
    }
    while (!siblings.add(name)) {
      name = name + "_";
    }
    return name;
  }

  /** Splits a key on anything that is not a letter or digit: "max-hp_2" becomes [max, hp, 2]. */
  private static String[] words(String key) {
    return key.split("[^\\p{L}\\p{N}]+");
  }

  private static String identifier(String[] words, boolean capitalizeFirst) {
    StringBuilder name = new StringBuilder();
    for (String word : words) {
      if (word.isEmpty()) {
        continue;
      }
      boolean capitalize = capitalizeFirst || name.length() > 0;
      name.append(capitalize ? Character.toUpperCase(word.charAt(0)) : word.charAt(0))
          .append(word, 1, word.length());
    }
    if (name.length() == 0 || !Character.isJavaIdentifierStart(name.charAt(0))) {
      name.insert(0, '_');
    }
    String result = name.toString();
    return SourceVersion.isKeyword(result) ? result + "_" : result;
  }

  private static String escape(String text) {
    return text.replace("\\", "\\\\").replace("\"", "\\\"");
  }

  private static String javadoc(String text) {
    return text.replace("*/", "*&#47;").replace("\n", " ").replace("@", "{@literal @}");
  }
}
